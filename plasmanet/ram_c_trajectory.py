"""Canonical RAM-C II trajectory grid — single source of truth.

The four reflectometer instrumentation points from Jones & Cross 1972
(NASA TN D-6617). Used by:

  - PDF report Validation section (plasmanet/pdf_report.py)
  - benchmark route reference n_e (plasmanet/mock_server.py via this dict)
  - frontend FlightSelectors (frontend/src/data/ram_c_trajectory.json,
    auto-generated by scripts/sync_trajectory_json.py)

To add or change a trajectory point: edit RAM_C_TRAJECTORY here, then run
`python scripts/sync_trajectory_json.py` to regenerate the frontend JSON.
A pytest contract test (tests/test_ram_c_trajectory.py) asserts the JSON
matches the Python module on every CI run, so drift is caught immediately.
"""
from __future__ import annotations

from typing import Optional, TypedDict


class TrajectoryPoint(TypedDict):
    altitude_km: float
    mach: float
    ne_peak_m3_published: float       # Jones & Cross 1972 reference
    source: str


# Listed altitude-descending — matches the J&C 1972 reflectometer table
# layout in the original NASA technical note.
RAM_C_TRAJECTORY: list[TrajectoryPoint] = [
    {
        "altitude_km": 81.0,
        "mach": 23.9,
        "ne_peak_m3_published": 2.0e18,
        "source": "Jones & Cross 1972 NASA TN D-6617",
    },
    {
        "altitude_km": 71.0,
        "mach": 23.6,
        "ne_peak_m3_published": 1.0e19,
        "source": "Jones & Cross 1972 NASA TN D-6617",
    },
    {
        "altitude_km": 61.0,
        "mach": 22.5,
        "ne_peak_m3_published": 2.0e19,
        "source": "Jones & Cross 1972 NASA TN D-6617 (primary validation point)",
    },
    {
        "altitude_km": 47.0,
        "mach": 18.5,
        "ne_peak_m3_published": 2.0e19,
        "source": "Jones & Cross 1972 NASA TN D-6617",
    },
]


# ── Convenience accessors ─────────────────────────────────────────────────────

def trajectory_altitudes() -> list[float]:
    """Distinct altitudes, ascending. Drives the frontend altitude pill row."""
    return sorted({pt["altitude_km"] for pt in RAM_C_TRAJECTORY})


def trajectory_machs() -> list[float]:
    """Distinct Mach numbers, ascending. Drives the frontend Mach pill row."""
    return sorted({pt["mach"] for pt in RAM_C_TRAJECTORY})


# ── Tuple-keyed reference dict ────────────────────────────────────────────────
# Matches the legacy CANONICAL_RAMC_POINTS shape from pdf_report.py so callers
# don't need to migrate. New code should prefer iterating RAM_C_TRAJECTORY
# directly, which carries the source citation alongside the values.

CANONICAL_RAMC_POINTS: dict[tuple[float, float], float] = {
    (pt["mach"], pt["altitude_km"]): pt["ne_peak_m3_published"]
    for pt in RAM_C_TRAJECTORY
}


def find_canonical_match(
    mach: float,
    altitude_km: float,
    *,
    mach_tol: float = 0.1,
    alt_tol_km: float = 1.0,
) -> Optional[tuple[float, float]]:
    """Return the closest canonical RAM-C trajectory point within tolerance.

    Returns None when (mach, altitude_km) is outside ±0.1 Mach and ±1 km of
    every canonical entry — caller should treat this as "off-grid", e.g.
    pass benchmark_log10_error=None to build_pdf so the Validation section
    stays hidden.
    """
    for (m, a) in CANONICAL_RAMC_POINTS:
        if abs(m - mach) <= mach_tol and abs(a - altitude_km) <= alt_tol_km:
            return (m, a)
    return None


